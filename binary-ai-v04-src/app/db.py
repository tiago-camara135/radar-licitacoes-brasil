def backend_name() -> str:
    return "Neon Postgres" if _pg() else "SQLite"


def _band(score: float) -> tuple[int, int]:
    s = max(0, min(99, int(score)))
    lo = (s // 5) * 5
    return lo, lo + 4


def wilson_interval(wins: int, total: int, z: float = 1.96) -> tuple[float | None, float | None]:
    if total <= 0:
        return None, None
    p = wins / total
    denom = 1 + z*z/total
    centre = (p + z*z/(2*total)) / denom
    margin = z * math.sqrt((p*(1-p) + z*z/(4*total))/total) / denom
    return max(0.0, centre-margin), min(1.0, centre+margin)


def calibration_for(broker: str, market: str, score: float, min_samples: int = 50) -> dict:
    lo, hi = _band(score)
    with _lock, _conn() as con:
        row = con.execute(_q("""SELECT COUNT(*), SUM(CASE WHEN status='WIN' THEN 1 ELSE 0 END)
            FROM broker_signals
            WHERE broker=? AND market=? AND status IN ('WIN','LOSS')
              AND technical_score>=? AND technical_score<?"""), (broker, market, lo, hi + 1)).fetchone()
    total = int(row[0] or 0); wins = int(row[1] or 0)
    posterior = (wins + 2) / (total + 4) if total else None
    low, high = wilson_interval(wins, total)
    return {
        "band": f"{lo}-{hi}", "samples": total, "wins": wins,
        "observed_rate": round(wins/total*100, 2) if total else None,
        "posterior_probability": round(posterior*100, 2) if posterior is not None else None,
        "ci95_low": round(low*100, 2) if low is not None else None,
        "ci95_high": round(high*100, 2) if high is not None else None,
        "ready": total >= min_samples,
        "min_samples": min_samples,
    }


def record_broker_signal(*, broker: str, venue: str, market: str, symbol: str, action: str, score: float,
                         payout: float | None, target_open_time: int, calibrated_probability: float | None = None) -> bool:
    if action not in {"CALL", "PUT"}:
        return False
    breakeven = 100.0 / (100.0 + payout) if payout and payout > 0 else None
    params = (int(time()), broker, venue, market, symbol, action, float(score), calibrated_probability,
              payout, breakeven, int(target_open_time), int(target_open_time)+60)
    with _lock, _conn() as con:
        if _pg():
            cur = con.execute("""INSERT INTO broker_signals(
                created_at,broker,venue,market,symbol,action,technical_score,calibrated_probability,payout,breakeven,target_open_time,target_close_time
            ) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
            ON CONFLICT (broker,symbol,target_open_time) DO NOTHING""", params)
            inserted = cur.rowcount > 0
        else:
            before = con.total_changes
            con.execute("""INSERT OR IGNORE INTO broker_signals(
                created_at,broker,venue,market,symbol,action,technical_score,calibrated_probability,payout,breakeven,target_open_time,target_close_time
            ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)""", params)
            inserted = con.total_changes > before
        con.commit()
        return inserted


def resolve_from_candles(broker: str, symbol: str, candles_1m: list[dict]) -> int:
    if not candles_1m:
        return 0
    by_time = {int(c["time"]): c for c in candles_1m}
    now = int(time())
    resolved = 0
    with _lock, _conn() as con:
        rows = con.execute(_q("""SELECT id, action, target_open_time FROM broker_signals
            WHERE broker=? AND symbol=? AND status='PENDING' AND target_close_time<=?"""), (broker, symbol, now)).fetchall()
        for rid, action, target_open in rows:
            candle = by_time.get(int(target_open))
            if not candle:
                continue
            op = float(candle["open"]); cl = float(candle["close"])
            if cl == op:
                status = "DRAW"
            elif action == "CALL":
                status = "WIN" if cl > op else "LOSS"
            else:
                status = "WIN" if cl < op else "LOSS"
            con.execute(_q("UPDATE broker_signals SET status=?, candle_open=?, candle_close=? WHERE id=?"), (status, op, cl, rid))
            resolved += 1
        con.commit()
    return resolved


def history(limit: int = 100, broker: str | None = None) -> dict:
    where, params = [], []
    if broker:
        where.append("broker=?"); params.append(broker)
    clause = " WHERE " + " AND ".join(where) if where else ""
    with _lock, _conn() as con:
        rows = con.execute(_q(f"""SELECT created_at,broker,market,symbol,action,technical_score,calibrated_probability,payout,
            target_open_time,status,candle_open,candle_close FROM broker_signals{clause} ORDER BY id DESC LIMIT ?"""), (*params, limit)).fetchall()
        agg_clause = clause + (" AND" if clause else " WHERE") + " status!='PENDING'"
        agg = con.execute(_q(f"""SELECT COUNT(*), SUM(CASE WHEN status='WIN' THEN 1 ELSE 0 END),
            SUM(CASE WHEN status='LOSS' THEN 1 ELSE 0 END), SUM(CASE WHEN status='DRAW' THEN 1 ELSE 0 END)
            FROM broker_signals{agg_clause}"""), params).fetchone()
    total,wins,losses,draws = [int(x or 0) for x in agg]
    return {
        "resolved": total, "wins": wins, "losses": losses, "draws": draws,
        "accuracy": round(wins/(wins+losses)*100,2) if (wins+losses) else None,
        "recent": [dict(zip(["created_at","broker","market","symbol","action","technical_score","calibrated_probability","payout","target_open_time","status","candle_open","candle_close"], r)) for r in rows]
    }


def calibration_table(broker: str | None = None, market: str | None = None) -> list[dict]:
    out=[]
    brokers = [broker] if broker else ["pocket","quotex","iqoption"]
    markets = [market] if market else ["otc","real"]
    for b in brokers:
        for m in markets:
            for lo in range(55, 91, 5):
                c = calibration_for(b,m,lo)
                if c["samples"]:
                    c.update({"broker":b,"market":m})
                    out.append(c)
    return out
